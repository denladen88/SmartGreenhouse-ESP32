// ---- I2C (шина сенсорів, Wire/I2C0 — див. SensorService::begin()) ----
#define I2C_SDA_PIN 1
#define I2C_SCL_PIN 2
constexpr unsigned long I2C_FREQ_HZ = 100000;

constexpr uint8_t BME280_ADDR_PRIMARY = 0x76;
constexpr uint8_t BME280_ADDR_SECONDARY = 0x77;
constexpr uint8_t BH1750_ADDR = 0x23;

// ---- Аналоговий вхід ----
// GPIO3, не GPIO14: GPIO14 сидить на ADC2, який на ESP32-S3 конфліктує з
// активним Wi-Fi-радіо (підтверджено на практиці — щойно Wi-Fi реально
// підключився й почав публікувати телеметрію, показники стрибали хаотично
// від ~0 до ~4095 щоцикл). GPIO3 — останній вільний ADC1-пін (GPIO1-10),
// решта зайняті I2C-шиною сенсорів і камерою; він є strapping-піном для
// вибору джерела JTAG на ESP32-S3, але це стосується лише самого reset,
// як звичайний аналоговий вхід після завантаження працює нормально.
constexpr int SOIL_ADC_PIN = 3;
constexpr int ADC_RESOLUTION_BITS = 12;

// Калібрування ґрунтового датчика (резистивний AZDelivery, з медіанним
// фільтром 15 зразків). SOIL_RAW_DRY=4095 стабільний і незмінний — на
// розімкненому колі (повітря) стан контактної поверхні зонда не має
// значення, опір і так "нескінченний". SOIL_RAW_WET перекалібровано:
// початково було ~0 у чистій воді, але після кількох цілодобових циклів
// тестування під постійною 3.3V контакти зонда скорродували (глибша
// корозія металу, не просто поверхнева плівка — чистка наждаком/спиртом
// вже не повертає до ~0), тож поточний стабільний еталон у воді — ~1270.
// Якщо калібрування знову "попливе" з часом — це та сама корозія,
// прогресуюча далі; довгострокове вирішення — не тримати зонд під
// постійною напругою (вмикати живлення лише на час виміру).
constexpr int SOIL_RAW_WET = 1270;
constexpr int SOIL_RAW_DRY = 4095;

// ---- Ґрунтовий термодатчик (DS18B20, OneWire) ----
// GPIO21: МАЄ бути пін <= 33. Бібліотека paulstoffregen/OneWire 2.3.8 у
// util/OneWire_direct_gpio.h (directModeOutput, рядок ~240) має перевірку
// `pin <= 33` — успадковану від ESP32 classic, де GPIO34-39 були тільки
// входами. На пінах >33 функція мовчки нічого не робить: лінія ніколи не
// перемикається у вихід, reset-імпульс не формується, presence немає,
// reset()==0, getDeviceCount()==0. На ESP32-S3 усі GPIO двонапрямлені, але
// бібліотека цього не враховує — тож GPIO38/39/40/41 тут не годяться.
// GPIO21 звільнено з-під вентилятора (той перенесено на GPIO40): вентилятор
// керується через digitalWrite() ядра Arduino, яке коректно працює на пінах
// >33, тож саме він, а не OneWire, іде на "високий" пін. Решта пінів <=33
// зайнята: камера 4-13/15-18, 26-37 октальна PSRAM/flash, 1-3 сенсори/ADC,
// 45/47 світло/помпа, 19/20 USB, 0/3 strapping.
constexpr int SOIL_TEMP_ONEWIRE_PIN = 21;

// ---- Підігрів ґрунту (DC грілка-мат через MOSFET-модуль, ШІМ) ----
// GPIO39: наступний вільний пін одразу за SOIL_TEMP_ONEWIRE_PIN (38), той
// самий безпечний діапазон (26-37 зайняті октальною PSRAM/flash-шиною
// модуля). Керується так само, як grow-світло (LIGHT_PIN) — окремий
// MOSFET-модуль на зовнішньому 12V/24V живленні, ESP32 лише подає ШІМ-сигнал.
#define SOIL_HEATER_PIN 39
constexpr int SOIL_HEATER_PWM_CHANNEL = 5; // канали 0 (камера) і 4 (світло) зайняті
constexpr int SOIL_HEATER_PWM_FREQ_HZ = 5000;
constexpr int SOIL_HEATER_PWM_RESOLUTION_BITS = 8; // потужність 0-255

// Захисний ліміт, як у вентилятора (FAN_MAX_RUNTIME_MS): нагрівач — це
// пожежонебезпечне навантаження без власного термостата, тож таймер
// оновлюється на КОЖНУ команду "увімкнено" (не лише перехід off->on) і
// примусово гасить нагрівач, якщо бекенд не підтвердив рішення довше цього
// часу (наприклад, мережа впала чи процес завис).
constexpr unsigned long SOIL_HEATER_MAX_RUNTIME_MS = 900000;

// ---- Підігрів повітря (12V PTC-нагрівач через MOSFET-модуль, ШІМ) ----
// GPIO42: JTAG MTMS за замовчуванням, але як звичайний GPIO працює — та сама
// група пінів, що FAN_PIN=40 (MTDO) і SOIL_HEATER_PIN=39 (MTCK). Піни 33-37
// зайняті октальною PSRAM модуля N16R8 (SPIIO4-7 + DQS) — туди актуатор чіпляти
// не можна, буде конфлікт шини PSRAM з буфером кадру камери. Керується як
// grow-світло / грілка ґрунту: окремий MOSFET-модуль на зовнішньому 12V,
// ESP32 лише подає ШІМ-сигнал.
#define AIR_HEATER_PIN 42
constexpr int AIR_HEATER_PWM_CHANNEL = 6; // канали 0 (камера), 4 (світло), 5 (ґрунт) зайняті
constexpr int AIR_HEATER_PWM_FREQ_HZ = 1000; // теплова маса велика, 5кГц як у ґрунтового зайві
constexpr int AIR_HEATER_PWM_RESOLUTION_BITS = 8; // потужність 0-255

// Той самий захисний ліміт, що у ґрунтового нагрівача (SOIL_HEATER_MAX_RUNTIME_MS):
// пожежонебезпечне навантаження без власного термостата, тож таймер оновлюється
// на КОЖНУ команду "увімкнено" і примусово гасить нагрівач, якщо бекенд не
// підтвердив рішення довше цього часу.
constexpr unsigned long AIR_HEATER_MAX_RUNTIME_MS = 900000;

// ---- Актуатори ----
constexpr int PUMP_RELAY_PIN = 47;
// GPIO40: перенесено з GPIO21 (той відданий під OneWire-датчик ґрунту, якому
// потрібен пін <=33 — див. SOIL_TEMP_ONEWIRE_PIN). Вентилятор — простий
// цифровий вихід через digitalWrite() ядра Arduino, яке коректно драйвить
// піни >33, тож "високий" пін безпечний саме для нього. GPIO40 за
// замовчуванням JTAG MTDO, але як звичайний GPIO працює.
constexpr int FAN_PIN = 40;

// Grow light: 24V біла стрічка (Philips Hue Lightstrip, RGB+TW), але з неї
// використовуються лише окремі аналогові канали Cold White (C) і Warm White
// (W) — це НЕ адресований WS2812-подібний протокол, це прямі лінії, кожна
// вмикається/тьмяниться через власний MOSFET-модуль. Обидва TRIG/PWM входи
// модулів сидять на одному GPIO (LIGHT_PIN) — один ШІМ-сигнал керує C і W
// одночасно єдиною яскравістю (без окремого регулювання кольорової
// температури). Керується виключно через MQTT-команду light_brightness
// (0-255) — жодної локальної автоматики по датчику освітленості немає.
#define LIGHT_PIN 45
constexpr int LED_PWM_CHANNEL = 4; // канали 0/timer 0 зайняті камерою (CameraService)
constexpr int LED_PWM_FREQ_HZ = 5000;
constexpr int LED_PWM_RESOLUTION_BITS = 8; // яскравість 0-255

// Штатна тривалість одного "пострілу" поливу: помпа вмикається імпульсом саме
// на цей час, а вимиканням керує сама прошивка (ActuatorService::update()
// щоцикл loop()) — бекенду достатньо надіслати pump_on:true, окрема команда
// "вимкнути" не потрібна. МАЄ лишатися меншим за PUMP_MAX_RUNTIME_MS.
constexpr unsigned long PUMP_RUN_DURATION_MS = 1000;

// Аварійний ліміт (backstop): якщо штатне вимкнення вище чомусь не спрацювало
// (баг у логіці, "залипання" реле, зависання команди) — помпа примусово
// гаситься через цей час. У нормі не досягається ніколи.
constexpr unsigned long PUMP_MAX_RUNTIME_MS = 5000;

// Той самий захист для вентилятора, але інша семантика, ніж у помпи: тут це
// "макс. час БЕЗ підтвердження від бекенда", а не "макс. безперервна робота".
// ActuatorService::setFan() оновлює таймер на КОЖНУ команду "on" (не лише на
// перехід OFF->ON) — тож поки локальний контролер на бекенді
// (AiAgronomistService.RunLocalControlAsync) підтверджує рішення щотіку
// (LocalControlIntervalMinutes, типово 10 хв), вентилятор працює безперервно,
// скільки потрібно. Гаситься лише якщо бекенд реально замовк (мережа впала,
// процес завис) і не надіслав жодної команди довше цього ліміту — 15 хв дає
// запас поверх 10-хвилинного циклу підтверджень.
constexpr unsigned long FAN_MAX_RUNTIME_MS = 900000;

